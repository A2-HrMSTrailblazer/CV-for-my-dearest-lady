// Sets the owner password.
// Usage: npm run set-password -- "your new password"
// Writes only a salted PBKDF2 hash to src/config.js; the password itself is never stored.
import { pbkdf2Sync, randomBytes } from 'node:crypto'
import { writeFileSync } from 'node:fs'

const pw = process.argv[2]
if (!pw || pw.length < 8) {
  console.error('Give a password of at least 8 characters:  npm run set-password -- "my new password"')
  process.exit(1)
}
const iterations = 210000
const salt = randomBytes(16).toString('hex')
const hash = pbkdf2Sync(pw, Buffer.from(salt, 'hex'), iterations, 32, 'sha256').toString('hex')

writeFileSync(
  new URL('../src/config.js', import.meta.url),
  `// Generated by scripts/set-password.mjs. Do not edit by hand.
// Holds a salted hash of the owner password, never the password itself.
export const OWNER_PASSWORD = {
  salt: '${salt}',
  iterations: ${iterations},
  hash: '${hash}'
}
`
)
console.log('Password updated in src/config.js. Rebuild and redeploy the site.')
